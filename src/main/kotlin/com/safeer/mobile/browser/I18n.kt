        val pref = PreferencesManager.getLanguage(context)
        if (pref != "auto" && SUPPORTED_LANGUAGES.containsKey(pref)) {
            return pref
        }
        val sysLang = Locale.getDefault().language.lowercase()
        return if (SUPPORTED_LANGUAGES.containsKey(sysLang)) sysLang else "en"
    }

    fun t(context: Context, key: String, defaultVal: String = ""): String {
        val lang = getEffectiveLanguage(context)
        val langMap = TRANSLATIONS[lang] ?: TRANSLATIONS["en"]!!
        return langMap[key] ?: TRANSLATIONS["en"]?.get(key) ?: defaultVal.ifEmpty { key }
    }
}
